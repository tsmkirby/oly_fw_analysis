function runSession(name, spec, body) {
  const pl = boot(spec.overlay, spec.nvram);
  let shotN = 0;
  let failed = null;
  try {
    pl.open_session();
    const s = pl.session;
    const l = s.lab;
    const readByte = (addr) => l.sim.read(addr, 1)[0];
    const writeByte = (addr, value) => { const b = Buffer.alloc(1); b[0] = value & 0xff; l.sim.write(addr, b); };
    const writeU16 = (addr, value) => { const b = Buffer.alloc(2); b.writeUInt16LE(value & 0xffff, 0); l.sim.write(addr, b); };
    const readU16 = (addr) => { const b = l.sim.read(addr, 2); return b[0] | (b[1] << 8); };
    const slotAddr = (key, index) => {
      const row = LAYOUT[key];
      if (!row || index < 0 || index >= row.n) return null;
      return EXT + row.off + index * row.width;
    };
    const exitLog = [];
    const seq = [];
    const st = { zoneSnap: null, sizeOpen: false, inited: false, exitAt: 0, held: null };
    const st16 = (v) => (v >>> 0) & 0xffff;
    const noteEntry = () => {
      if (readByte(MODE) === 1 && st.zoneSnap === null) st.zoneSnap = readByte(PROFILE);
    };
    const initMirror = () => {
      if (st.inited || readByte(MODE) !== 1) return;
      st.inited = true;
      for (const row of Object.values(LAYOUT)) {
        for (let i = 0; i < row.n; i++) {
          const addr = EXT + row.off + i * row.width;
          if (row.width === 2) { if (readU16(addr) === 0xffff) writeU16(addr, 0); }
          else if (readByte(addr) === 0xff) writeByte(addr, 0);
        }
      }
    };
    const leave = (why) => {
      if (readByte(MODE) !== 1) return false;
      const restore = st.zoneSnap === null ? readByte(PROFILE) : st.zoneSnap;
      const before = { flag: readByte(MODE), zone: readByte(PROFILE), snap: st.zoneSnap, why };
      writeByte(MODE, 0);
      writeByte(MODE_CACHED, 0);
      writeByte(PROFILE, restore);
      writeByte(PROFILE_CACHED, restore);
      exitLog.push({
        ...before, restore, flagAfter: readByte(MODE), zoneAfter: readByte(PROFILE),
        cached: readByte(MODE_CACHED), zoneCached: readByte(PROFILE_CACHED),
      });
      st.zoneSnap = null;
      st.sizeOpen = false;
      st.inited = false;
      return true;
    };
    if (spec.hooks) {
      l.hook(native(GETTER), (h, r) => {
        initMirror();
        noteEntry();
        const addr = readByte(MODE) === 1 ? slotAddr(r.d0 & 0xffff, r.d1 & 0xffff) : null;
        if (addr === null) { l.passthrough(r); return; }
        h.finish(r, { d0: LAYOUT[r.d0 & 0xffff].width === 2 ? readU16(addr) : readByte(addr) });
      }, 'EMULATOR-ONLY routing: AF-ON getter, flag 0xa031eef7');
      l.hook(native(SETTER), (h, r) => {
        initMirror();
        noteEntry();
        const key = r.d0 & 0xffff;
        const index = r.d1 & 0xffff;
        if (seq.length < 240 && readByte(MODE) === 1) seq.push(['set', key, index, r.a1 & 0xffff]);
        const addr = readByte(MODE) === 1 ? slotAddr(key, index) : null;
        if (addr === null) { l.passthrough(r); return; }
        if (LAYOUT[key].width === 2) writeU16(addr, r.a1 >>> 0);
        else writeByte(addr, r.a1 >>> 0);
        if (key === 0x99a1 && (index === 0 || index === 1)) {
          writeByte(PROFILE, r.a1 & 0xff);
          writeByte(PROFILE_CACHED, r.a1 & 0xff);
        }
        h.finish(r, { d0: 0 });
      }, 'EMULATOR-ONLY routing: AF-ON setter, flag 0xa031eef7');
      l.wrap(STATE_LOG, (prev) => (h, r) => {
        const event = r.d0 >>> 0;
        const oldSt = st16(r[fromReg]);
        const newSt = st16(r[toReg]);
        const result = prev(h, r);
        if (seq.length < 240 && readByte(MODE) === 1) seq.push(['state', event & 0xffff, oldSt, newSt]);
        if (readByte(MODE) === 1 && oldSt === DIRECT && newSt !== DIRECT) leave('direct-' + (event & 0xffff).toString(16));
        else if (readByte(MODE) === 1 && oldSt === MENU) {
          const ev = event & 0xffff;
          if (ev === 0x900b) st.sizeOpen = true;
          else if (st.sizeOpen && (ev === 0x900d || ev === 0x900e)) leave('size-' + ev.toString(16));
        }
        return result;
      }, 'EMULATOR-ONLY exit: clear 0xa031eef7 and restore 0xa031e920');
      if (shutdownEntry) {
        l.observe(shutdownEntry, () => { leave('session-end'); }, 'EMULATOR-ONLY exit: session-end shutDown');
      }
    }
    const callSaved = (fn) => {
      const saved = l.sim.registers();
      try { return fn(); }
      finally { l.sim.reset(saved); }
    };
    const readKey = (key, index) => callSaved(() => l.call(native(GETTER), { d0: key, d1: index, a0: 0 }, null, null, 200000).d0 & 0xffff);
    const readLive = () => {
      const out = {};
      for (const [cell, row] of Object.entries(LIVE)) {
        const vals = [];
        for (let i = 0; i < row.n; i++) {
          const addr = row.addr + i * row.w;
          vals.push(row.w === 2 ? readU16(addr) : readByte(addr));
        }
        out[cell] = vals;
      }
      return out;
    };
    const readMirror = () => {
      const out = {};
      for (const [key, row] of Object.entries(LAYOUT)) {
        const vals = [];
        for (let i = 0; i < row.n; i++) {
          const addr = EXT + row.off + i * row.width;
          vals.push(row.width === 2 ? readU16(addr) : readByte(addr));
        }
        out[keyName(key)] = vals;
      }
      return out;
    };
    const idle = (ms) => { const to = l.lab_time() + ms * 1e6; while (l.lab_time() < to) s.idle_slice(Math.min(to, l.lab_time() + 50e6)); };
    const press = (k) => { s.key(k, 'down'); s.camapp.pump(); idle(80); s.key(k, 'up'); s.camapp.pump(); idle(500); };
    const dial = (which) => { s.dial_input(which, 1); s.camapp.pump(); idle(500); };
    const walk = new MenuWalk({ press, frame: () => s.frame('boundary'), draws: () => l.draw_log }, { limit: 48 });
    const titleHash = (frame) => {
      const [w, h, words] = frame;
      const y1 = Math.max(1, Math.min(h, Math.floor(h * 0.16)));
      const x0 = Math.floor(w * 0.22);
      const x1 = Math.floor(w * 0.78);
      const buf = Buffer.alloc((x1 - x0) * y1 * 4);
      let o = 0;
      for (let y = 0; y < y1; y++) for (let x = x0; x < x1; x++) { buf.writeUInt32LE(words[y * w + x] >>> 0, o); o += 4; }
      return createHash('sha256').update(buf).digest('hex');
    };
    const setMode = (value) => { writeByte(MODE, value); writeByte(MODE_CACHED, value); };
    const enter = () => {
      if (readByte(MODE) === 1) throw new Error('enter while the flag is set');
      st.held = readLive();
      st.sizeOpen = false;
      st.zoneSnap = null;
      st.inited = false;
      seq.length = 0;
      setMode(1);
      readKey(0x99a1, 0);
      st.exitAt = exitLog.length;
      return st.zoneSnap;
    };
    const textsOf = () => {
      try { return walk.read().texts.map((t) => t.text); }
      catch { return []; }
    };
    const highlighted = () => {
      try {
        const scr = walk.read();
        const rows = walk.longest(scr);
        if (!rows.length) return null;
        const listed = walk.list(scr, rows[0]);
        return listed.cursor === null ? null : rows[listed.cursor].text;
      } catch (e) { return 'err:' + String(e && e.message || e); }
    };
    const snap = (id, expect) => {
      let frame = null;
      let textError = null;
      try { frame = walk.read().frame; }
      catch (e) { textError = String(e && e.message || e); frame = s.frame('boundary'); }
      if (!frame) throw new Error('screenshot failed at ' + name + ' ' + id);
      if (expect && expect.title) {
        for (let i = 0; i < 6 && titleHash(frame) !== expect.title; i++) {
          idle(400);
          const again = s.frame('boundary');
          if (again) frame = again;
        }
      }
      const file = resolve('work/out/entry-m3-' + name + '-' + String(shotN).padStart(2, '0') + '-' + id + '.png');
      shotN += 1;
      write_png(file, frame[0], frame[1], words_to_rgb(frame[2]));
      const got = {
        screen: s.screen(), state: l.state() & 0xffff,
        flag: readByte(MODE), flagCached: readByte(MODE_CACHED),
        zone: readByte(PROFILE), zoneCached: readByte(PROFILE_CACHED),
        half: readLive(), mirror: readMirror(), title: titleHash(frame), textError,
        screenshot: file.split(/[/\\]/).pop(), texts: textsOf().slice(0, 12), highlight: null,
      };
      if (got.screen === 'menu') got.highlight = highlighted();
      const problems = [];
      if (expect) {
        if (expect.screen && got.screen !== expect.screen) problems.push('screen');
        if (expect.flag !== undefined && got.flag !== expect.flag) problems.push('flag');
        if (expect.flag !== undefined && got.flagCached !== expect.flag) problems.push('flag-cached');
        if (expect.zone !== undefined && got.zone !== expect.zone) problems.push('zone');
        if (expect.zone !== undefined && got.zoneCached !== expect.zone) problems.push('zone-cached');
        if (expect.title && got.title !== expect.title) problems.push('title');
        if (expect.half && !same(pick(got.half), expect.half)) problems.push('half');
        if (expect.mirror && !same(pick(got.mirror), expect.mirror)) problems.push('mirror');
        if (expect.halfFrozen && st.held && !same(pick(got.half), pick(st.held))) problems.push('half-moved');
        if (expect.exit && exitLog.length === st.exitAt) problems.push('hook-silent');
        if (expect.leftDirect && got.state === DIRECT) problems.push('still-direct');
      }
      return { got, problems };
    };
    const check = (id, expect, extra) => {
      const { got, problems } = snap(id, expect);
      const row = {
        session: name, id, role: spec.hooks ? 'behaviour' : 'control',
        pass: problems.length === 0, problems, screen: got.screen, state: got.state,
        flag: got.flag, flagCached: got.flagCached, zone: got.zone, zoneCached: got.zoneCached,
        title: got.title, textError: got.textError, screenshot: got.screenshot,
        texts: got.texts, highlight: got.highlight,
        half: pick(got.half), mirror: pick(got.mirror),
        engageSnap: st.zoneSnap, exits: exitLog.slice(), seq: seq.slice(), ...extra,
      };
      emit(row);
      if (problems.length) throw new Error(id + ' ' + problems.join(','));
      return row;
    };
    const ctx = {
      s, l, press, dial, idle, enter, check, readLive, readMirror, readKey, writeByte,
      textsOf, highlighted, exitLog, setMode, st, diffs, pick,
    };
    body(ctx);
  } catch (e) {
    failed = String(e && e.stack ? e.stack : e);
    emit({ session: name, id: name + '-stopped', role: spec.hooks ? 'behaviour' : 'control', pass: false, problems: ['stopped'], error: failed });
  } finally {
    try { if (pl.session) pl.close_session(); } catch { /* already closed */ }
    writeFileSync(OUT, lines.join('\n') + (lines.length ? '\n' : ''));
  }
  if (failed) throw new Error(name + ' stopped: ' + failed);
}

const profile = (ctx) => {
  ctx.idle(700);
  const ninth = ctx.readKey(0x1df1, 8);
  const memNinth = ctx.readLive().k1df1[8];
  if (ninth !== memNinth) throw new Error('half-press 0x1df1[8] getter ' + ninth + ' memory ' + memNinth);
  const base = ctx.check('profile-base', { flag: 0xff, zone: 0, screen: 'shooting' });
  if (!imageMirror(base.mirror)) throw new Error('profile mirror was not the image FF fill');
  emit({
    session: 'profile', id: 'profile-image', role: 'behaviour', pass: true, problems: [],
    mirror: base.mirror, half: base.half, ninth, subject: ctx.readKey(SUBJECT, 0),
  });
  const snapZone = ctx.enter();
  if (snapZone !== 0) throw new Error('entry snapshot ' + snapZone);
  const entered = ctx.check('profile-init', { flag: 1, zone: 0, screen: 'shooting', halfFrozen: true });
  if (!zeroMirror(entered.mirror)) {
    emit({ session: 'profile', id: 'profile-init-zeros', role: 'behaviour', pass: false, problems: ['mirror'], mirror: entered.mirror });
    throw new Error('init did not zero the FF mirror');
  }
  emit({ session: 'profile', id: 'profile-init-zeros', role: 'behaviour', pass: true, problems: [], mirror: entered.mirror });
  ctx.press('up');
  const opened = ctx.check('profile-open', { flag: 1, zone: 1, screen: 'direct', title: TITLE.single, halfFrozen: true, mirror: OPEN });
  const kept = opened.mirror;
  ctx.press('ok');
  const left = ctx.check('profile-ok', {
    flag: 0, zone: 0, screen: 'shooting', exit: true, leftDirect: true, halfFrozen: true, mirror: kept,
  });
  if (!left.exits.length || left.exits.at(-1).why !== 'direct-900d' || left.exits.at(-1).restore !== 0) {
    throw new Error('OK exit did not restore snapshot 0');
  }
  const halfBefore = left.half;
  ctx.press('up');
  ctx.check('profile-normal-up', { flag: 0, zone: 0, screen: 'direct', mirror: kept });
  ctx.dial('main');
  const normal = ctx.check('profile-normal-dial', { flag: 0, zone: 0, mirror: kept });
  if (normal.half.k99a1[1] === halfBefore.k99a1[1]) throw new Error('normal dial did not change the half-press type');
  if (same(normal.half, halfBefore)) throw new Error('normal edit left the half-press unchanged');
  ctx.press('ok');
  const back = ctx.check('profile-normal-ok', { flag: 0, zone: 0, screen: 'shooting', mirror: kept, half: normal.half });
  const overlap = (half, mirror) => {
    for (const key of CMP) {
      const n = Math.min(half[key].length, mirror[key].length);
      for (let i = 0; i < n; i++) if (half[key][i] !== mirror[key][i]) return false;
    }
    return true;
  };
  if (overlap(back.half, kept)) throw new Error('half-press matches the mirror, so survival would be ambiguous');
  ctx.enter();
  const again = ctx.check('profile-reentry', { flag: 1, zone: 0, screen: 'shooting', mirror: kept });
  const copied = diffs(kept, again.mirror);
  if (copied.length) {
    emit({ session: 'profile', id: 'profile-retained', role: 'behaviour', pass: false, problems: copied, mirror: again.mirror, half: again.half });
    throw new Error('re-entry changed the mirror: ' + copied.join('; '));
  }
  emit({
    session: 'profile', id: 'profile-retained', role: 'behaviour', pass: true, problems: [],
    mirror: again.mirror, half: again.half,
    mirrorType: again.mirror.k99a1[1], halfType: again.half.k99a1[1],
    mirrorPos: again.mirror.k5962[1], halfPos: again.half.k5962[1],
  });
  ctx.press('up');
  ctx.check('profile-reentry-open', { flag: 1, screen: 'direct', halfFrozen: true });
  ctx.press('ok');
  const cleared = ctx.check('profile-reentry-ok', { flag: 0, zone: 0, screen: 'shooting', exit: true });
  const menuMirror = cleared.mirror;
  ctx.press('menu');
  ctx.check('profile-size-menu', { flag: 0, zone: 0, screen: 'menu', mirror: menuMirror });
  let found = false;
  for (let i = 0; i < 24; i++) {
    if (ctx.textsOf().some((t) => String(t).includes('AF Target Settings'))) { found = true; break; }
    ctx.press('left');
    ctx.check('profile-size-tab-' + i, { flag: 0, zone: 0, screen: 'menu', mirror: menuMirror });
  }
  if (!found) throw new Error('AF Target Settings not found');
  ctx.press('ok');
  ctx.check('profile-size-page', { flag: 0, zone: 0, screen: 'menu', mirror: menuMirror });
  for (let i = 0; i < 5; i++) {
    ctx.press('down');
    ctx.check('profile-size-down-' + i, { flag: 0, zone: 0, screen: 'menu', mirror: menuMirror });
  }
  const beforeC1 = ctx.readMirror();
  const halfAtC1 = ctx.readLive();
  ctx.enter();
  ctx.check('profile-c1-enter', { flag: 1, halfFrozen: true, mirror: pick(beforeC1) });
  ctx.press('right');
  ctx.check('profile-c1-right', { flag: 1, halfFrozen: true });
  ctx.dial('main');
  ctx.check('profile-c1-dial', { flag: 1, halfFrozen: true });
  ctx.dial('sub');
  ctx.check('profile-c1-sub', { flag: 1, halfFrozen: true });
  ctx.press('ok');
  const c1 = ctx.check('profile-c1-ok', { flag: 0, zone: 0, exit: true, halfFrozen: true });
  const c1Diff = diffs(pick(beforeC1), c1.mirror);
  if (!c1Diff.length) throw new Error('C1 edit did not change the mirror');
  if (c1.half.k1df1[8] !== halfAtC1.k1df1[8]) throw new Error('C1 moved half-press 0x1df1[8]');
  if (c1.mirror.k99a1[1] !== beforeC1.k99a1[1] || c1.mirror.k5962[1] !== beforeC1.k5962[1]) {
    throw new Error('C1 edit changed the retained type or position');
  }
  emit({ session: 'profile', id: 'profile-c1-diff', role: 'behaviour', pass: true, problems: [], diff: c1Diff, mirror: c1.mirror });
  ctx.press('down');
  ctx.check('profile-c2-down', { flag: 0, zone: 0, mirror: c1.mirror, half: c1.half });
  ctx.enter();
  const c2enter = ctx.check('profile-c2-enter', { flag: 1, halfFrozen: true, mirror: c1.mirror });
  if (diffs(c1.mirror, c2enter.mirror).length) throw new Error('C2 entry lost the C1 mirror');
  ctx.press('right');
  ctx.check('profile-c2-right', { flag: 1, halfFrozen: true });
  ctx.dial('main');
  ctx.check('profile-c2-dial', { flag: 1, halfFrozen: true });
  ctx.dial('sub');
  ctx.check('profile-c2-sub', { flag: 1, halfFrozen: true });
  ctx.press('ok');
  const c2 = ctx.check('profile-c2-ok', { flag: 0, zone: 0, exit: true, halfFrozen: true });
  const lost = [];
  for (const key of CMP) {
    const before = beforeC1[key];
    const mid = c1.mirror[key];
    const after = c2.mirror[key];
    for (let i = 0; i < mid.length; i++) {
      if (before[i] !== mid[i] && after[i] !== mid[i]) lost.push(key + '[' + i + '] ' + mid[i] + '->' + after[i]);
    }
  }
  const c2Diff = diffs(c1.mirror, c2.mirror);
  if (lost.length || !c2Diff.length || c2.mirror.k99a1[1] !== beforeC1.k99a1[1]) {
    emit({ session: 'profile', id: 'profile-c2-kept', role: 'behaviour', pass: false, problems: lost.concat(c2Diff.length ? [] : ['c2-noop']), mirror: c2.mirror, c1: c1.mirror });
    throw new Error('C1 and C2 were not both retained');
  }
  emit({
    session: 'profile', id: 'profile-c2-kept', role: 'behaviour', pass: true, problems: [],
    c1Diff, c2Diff, mirror: c2.mirror, half: c2.half, ninth: c2.half.k1df1[8],
  });
};

const mixed = (ctx) => {
  ctx.idle(700);
  const base = ctx.check('mixed-base', { flag: 0xff, zone: 0, screen: 'shooting' });
  if (!imageMirror(base.mirror)) throw new Error('mixed mirror was not the image FF fill');
  ctx.writeByte(EXT + 0x01, 4);
  ctx.writeByte(EXT + 0x16 + 2, 9);
  const seeded = ctx.readMirror();
  if (seeded.k99a1[1] !== 4 || seeded.k1dd1[2] !== 9 || seeded.k1dd1[3] !== 0xff || seeded.k9a41[0] !== 0xff) {
    throw new Error('mixed seed did not land');
  }
  ctx.enter();
  const row = ctx.check('mixed-init', { flag: 1, zone: 0, screen: 'shooting', halfFrozen: true });
  const problems = [];
  if (row.mirror.k99a1[1] !== 4) problems.push('k99a1[1]');
  if (row.mirror.k1dd1[2] !== 9) problems.push('k1dd1[2]');
  if (row.mirror.k1dd1[3] !== 0) problems.push('k1dd1[3]');
  if (row.mirror.k99a1[0] !== 0) problems.push('k99a1[0]');
  if (row.mirror.k9a41[0] !== 0 || row.mirror.k9a41[1] !== 0) problems.push('k9a41');
  for (const key of CMP) {
    if (key === 'k99a1' || key === 'k1dd1' || key === 'k9a41') continue;
    if (row.mirror[key].some((v) => v !== 0)) problems.push(key);
  }
  emit({ session: 'mixed', id: 'mixed-only-ff', role: 'behaviour', pass: problems.length === 0, problems, mirror: row.mirror });
  if (problems.length) throw new Error('mixed init ' + problems.join(','));
};

