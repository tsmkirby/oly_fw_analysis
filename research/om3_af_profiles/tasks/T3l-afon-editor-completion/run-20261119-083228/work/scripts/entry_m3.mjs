// Experiment m3. The same one behaviour change as m1, EMULATOR-ONLY.
// No new behaviour. m1 zeroed an FF mirror. m2 showed the first Up draws
// Single and writes OPEN, and that a further main-dial detent writes
// nothing while 0x5a11 is the descriptor zero. This run uses that Up as
// the type change and the move, then checks retention, C1 and C2, a mixed
// mirror, and a non-zero zone snapshot.
// AF-ON entry copies nothing into the mirror. A mirror byte that is still
// 0xFF, or a mirror word that is still 0xFFFF, becomes the descriptor
// default 0. Every other mirror byte stays. The exit hook is the accepted
// l6 hook. The harness never clears the flag and never writes the
// half-press into the mirror.
// Do not edit this file after it has run.
// Usage: node26 work/scripts/entry_m3.mjs om-emu
