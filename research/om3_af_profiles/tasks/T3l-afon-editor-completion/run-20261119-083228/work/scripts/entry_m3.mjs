const diffs = (a, b) => {
  const out = [];
  for (const key of CMP) {
    const left = a[key] || [];
    const right = b[key] || [];
    const n = Math.max(left.length, right.length);
    for (let i = 0; i < n; i++) if (left[i] !== right[i]) out.push(key + '[' + i + '] ' + left[i] + '->' + right[i]);
  }
  return out;
};
const imageMirror = (mirror) => {
  for (const [key, row] of Object.entries(LAYOUT)) {
    const vals = mirror[keyName(key)];
    const blank = row.width === 2 ? 0xffff : 0xff;
    if (!vals || vals.length !== row.n || vals.some((v) => v !== blank)) return false;
  }
  return true;
};
const zeroMirror = (mirror) => CMP.every((key) => {
  const vals = mirror[key];
  return vals && vals.length === LAYOUT[Number('0x' + key.slice(1))].n && vals.every((v) => v === 0);
});

const IMPORT_RE = /(?:from\s+|import\s*\(\s*|import\s+)['"]([^'"]+)['"]/g;
const USE_RE = /use\(\s*['"]([^'"]+)['"]\s*\)/g;
function resolveSpec(fromFile, spec) {
  if (!spec.startsWith('.')) return null;
  const base = resolve(dirname(fromFile), spec);
  for (const candidate of [base, base + '.mjs', base + '.js', join(base, 'index.mjs'), join(base, 'index.js')]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}
function inventory(files) {
  const seen = new Map();
  const queue = [...files];
  while (queue.length) {
    const cur = queue.pop();
    if (!cur || seen.has(cur) || !existsSync(cur)) continue;
    const data = readFileSync(cur);
    seen.set(cur, { sha256: createHash('sha256').update(data).digest('hex'), bytes: data.length });
    const text = data.toString('utf8');
    for (const re of [IMPORT_RE, USE_RE]) {
      re.lastIndex = 0;
      let match;
      while ((match = re.exec(text))) {
        const spec = match[1];
        const next = spec.startsWith('.') ? resolveSpec(cur, spec) : resolve(checkout, 'emu', spec);
        if (next && existsSync(next)) queue.push(next);
      }
    }
  }
  return [...seen.entries()].map(([path, meta]) => ({ path: path.replaceAll('\\', '/'), ...meta, hashed: 'execution' }));
}

