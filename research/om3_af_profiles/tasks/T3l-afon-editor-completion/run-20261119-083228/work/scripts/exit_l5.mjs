function runSession(name, spec, body) {
  const pl = boot(spec.overlay, spec.nvram);
  let shotN = 0;
  let failed = null;
  try {
    pl.open_session();
    const s = pl.session;
    const l = s.lab;
    const readByte = (addr) => l.sim.read(addr, 1)[0];
    const writeByte = (addr, value) => { const b = Buffer.alloc(1); b[0] = value & 0xff; l.sim.write(addr, b); };
    const writeU16 = (addr, value) => { const b = Buffer.alloc(2); b.writeUInt16LE(value & 0xffff, 0); l.sim.write(addr, b); };
    const readU16 = (addr) => { const b = l.sim.read(addr, 2); return b[0] | (b[1] << 8); };
    const slotAddr = (key, index) => {
      const row = LAYOUT[key];
      if (!row || index < 0 || index >= row.n) return null;
      return EXT + row.off + index * row.width;
    };
    const exitLog = [];
    const seq = [];
    let zoneSnap = null;
    let sizeOpen = false;
    let exitAt = 0;
    const st16 = (v) => (v >>> 0) & 0xffff;
    const noteEntry = () => {
      if (readByte(MODE) === 1 && zoneSnap === null) zoneSnap = readByte(PROFILE);
    };
    const leave = (why) => {
      if (readByte(MODE) !== 1) return false;
      const restore = zoneSnap === null ? readByte(0x6295946d) : zoneSnap;
      const before = { flag: readByte(MODE), zone: readByte(PROFILE), snap: zoneSnap, why };
      writeByte(MODE, 0);
      writeByte(MODE_CACHED, 0);
      writeByte(PROFILE, restore);
      writeByte(PROFILE_CACHED, restore);
      exitLog.push({ ...before, restore, flagAfter: readByte(MODE), zoneAfter: readByte(PROFILE), cached: readByte(MODE_CACHED), zoneCached: readByte(PROFILE_CACHED) });
      zoneSnap = null;
      sizeOpen = false;
      return true;
    };
    if (spec.hooks) {
      l.hook(native(GETTER), (h, r) => {
        noteEntry();
        const addr = readByte(MODE) === 1 ? slotAddr(r.d0 & 0xffff, r.d1 & 0xffff) : null;
        if (addr === null) { l.passthrough(r); return; }
        h.finish(r, { d0: LAYOUT[r.d0 & 0xffff].width === 2 ? readU16(addr) : readByte(addr) });
      }, 'EMULATOR-ONLY routing: AF-ON getter, flag 0xa031eef7');
      l.hook(native(SETTER), (h, r) => {
        noteEntry();
        const key = r.d0 & 0xffff;
        const index = r.d1 & 0xffff;
        if (seq.length < 200 && readByte(MODE) === 1) seq.push(['set', key, index, r.a1 & 0xffff]);
        const addr = readByte(MODE) === 1 ? slotAddr(key, index) : null;
        if (addr === null) { l.passthrough(r); return; }
        if (LAYOUT[key].width === 2) writeU16(addr, r.a1 >>> 0);
        else writeByte(addr, r.a1 >>> 0);
        if (key === 0x99a1 && (index === 0 || index === 1)) {
          writeByte(PROFILE, r.a1 & 0xff);
          writeByte(PROFILE_CACHED, r.a1 & 0xff);
        }
        h.finish(r, { d0: 0 });
      }, 'EMULATOR-ONLY routing: AF-ON setter, flag 0xa031eef7');
      l.wrap(STATE_LOG, (prev) => (h, r) => {
        const event = r.d0 >>> 0;
        const oldSt = st16(r[fromReg]);
        const newSt = st16(r[toReg]);
        const result = prev(h, r);
        if (seq.length < 200 && readByte(MODE) === 1) seq.push(['state', event & 0xffff, oldSt, newSt]);
        if (readByte(MODE) === 1 && oldSt === DIRECT && newSt !== DIRECT) leave('direct-' + (event & 0xffff).toString(16));
        else if (readByte(MODE) === 1 && oldSt === MENU) {
          const ev = event & 0xffff;
          if (ev === 0x900b) sizeOpen = true;
          else if (sizeOpen && (ev === 0x900d || ev === 0x900e)) leave('size-' + ev.toString(16));
        }
        return result;
      }, 'EMULATOR-ONLY exit: clear 0xa031eef7 and restore 0xa031e920');
      if (shutdownEntry) {
        l.observe(shutdownEntry, () => { leave('session-end'); }, 'EMULATOR-ONLY exit: session-end shutDown');
      }
    }
    const callSaved = (fn) => {
      const saved = l.sim.registers();
      try { return fn(); }
      finally { l.sim.reset(saved); }
    };
    const readKey = (key, index) => callSaved(() => l.call(native(GETTER), { d0: key, d1: index, a0: 0 }, null, null, 200000).d0 & 0xffff);
    const writeKey = (key, index, value) => callSaved(() => l.call(native(SETTER), { d0: key, d1: index, a1: value }, null, null, 200000));
    const readLive = () => {
      const out = {};
      for (const [name, row] of Object.entries(LIVE)) {
        const vals = [];
        for (let i = 0; i < row.n; i++) {
          const addr = row.addr + i * row.w;
          vals.push(row.w === 2 ? readU16(addr) : readByte(addr));
        }
        out[name] = vals;
      }
      return out;
    };
    const readMirror = () => {
      const out = {};
      for (const [key, row] of Object.entries(LAYOUT)) {
        const vals = [];
        for (let i = 0; i < row.n; i++) {
          const addr = EXT + row.off + i * row.width;
          vals.push(row.width === 2 ? readU16(addr) : readByte(addr));
        }
        out['k' + Number(key).toString(16)] = vals;
      }
      return out;
    };
    const idle = (ms) => { const to = l.lab_time() + ms * 1e6; while (l.lab_time() < to) s.idle_slice(Math.min(to, l.lab_time() + 50e6)); };
    const press = (k) => { s.key(k, 'down'); s.camapp.pump(); idle(80); s.key(k, 'up'); s.camapp.pump(); idle(500); };
    const dial = (which) => { s.dial_input(which, 1); s.camapp.pump(); idle(500); };
    const walk = new MenuWalk({ press, frame: () => s.frame('boundary'), draws: () => l.draw_log }, { limit: 8 });
    const titleHash = (frame) => {
      const [w, h, words] = frame;
      const y1 = Math.max(1, Math.min(h, Math.floor(h * 0.16)));
      const x0 = Math.floor(w * 0.22);
      const x1 = Math.floor(w * 0.78);
      const buf = Buffer.alloc((x1 - x0) * y1 * 4);
      let o = 0;
      for (let y = 0; y < y1; y++) for (let x = x0; x < x1; x++) { buf.writeUInt32LE(words[y * w + x] >>> 0, o); o += 4; }
      return createHash('sha256').update(buf).digest('hex');
    };
    const setMode = (value) => { writeByte(MODE, value); writeByte(MODE_CACHED, value); };
    let held = null;
    let engageSnap = null;
    const engage = () => {
      const live = readLive();
      const mirrorSrc = {};
      for (const [key, row] of Object.entries(LAYOUT)) {
        const name = 'k' + key.toString(16);
        const vals = [];
        for (let i = 0; i < row.n; i++) vals.push(readKey(key, i));
        mirrorSrc[name] = vals;
      }
      sizeOpen = false;
      zoneSnap = null;
      seq.length = 0;
      setMode(1);
      for (const [key, row] of Object.entries(LAYOUT)) {
        const vals = mirrorSrc['k' + key.toString(16)];
        for (let i = 0; i < row.n; i++) writeKey(Number(key), i, vals[i]);
      }
      engageSnap = zoneSnap;
      held = live;
      seq.length = 0;
      exitAt = exitLog.length;
      return live;
    };
    const textsOf = () => {
      try { return walk.read().texts.map((t) => t.text); }
      catch { return []; }
    };
    const snap = (id, expect) => {
      let frame = null;
      let textError = null;
      try { frame = walk.read().frame; }
      catch (e) { textError = String(e && e.message || e); frame = s.frame('boundary'); }
      if (!frame) throw new Error('screenshot failed at ' + name + ' ' + id);
      if (expect && expect.title) {
        for (let i = 0; i < 6 && titleHash(frame) !== expect.title; i++) {
          idle(400);
          const again = s.frame('boundary');
          if (again) frame = again;
        }
      }
      const file = resolve('work/out/exit-l5-' + name + '-' + String(shotN).padStart(2, '0') + '-' + id + '.png');
      shotN += 1;
      write_png(file, frame[0], frame[1], words_to_rgb(frame[2]));
      const flag = readByte(MODE);
      const flagCached = readByte(MODE_CACHED);
      const zone = readByte(PROFILE);
      const zoneCached = readByte(PROFILE_CACHED);
      const half = readLive();
      const mirror = readMirror();
      const got = {
        screen: s.screen(), state: l.state() & 0xffff, flag, flagCached, zone, zoneCached,
        half, mirror, title: titleHash(frame), textError,
        screenshot: file.split(/[/\\]/).pop(), texts: textsOf().slice(0, 8),
      };
      const problems = [];
      if (expect) {
        if (expect.screen && got.screen !== expect.screen) problems.push('screen');
        if (expect.screenNot && got.screen === expect.screenNot) problems.push('screen-not');
        if (expect.flag !== undefined && got.flag !== expect.flag) problems.push('flag');
        if (expect.flag !== undefined && got.flagCached !== expect.flag) problems.push('flag-cached');
        if (expect.zone !== undefined && got.zone !== expect.zone) problems.push('zone');
        if (expect.zoneRestored && got.zone !== engageSnap) problems.push('zone-restore');
        if (expect.zoneRestored && got.zoneCached !== engageSnap) problems.push('zone-cached');
        if (expect.title && got.title !== expect.title) problems.push('title');
        if (expect.halfFrozen && held && !same(pick(got.half), pick(held))) problems.push('half-moved');
        if (expect.exit && exitLog.length === exitAt) problems.push('hook-silent');
        if (expect.leftDirect && (got.state === DIRECT)) problems.push('still-direct');
      }
      return { got, problems };
    };
    const check = (id, expect, extra) => {
      const { got, problems } = snap(id, expect);
      const row = {
        session: name, id, role: spec.hooks ? 'behaviour' : 'control',
        pass: problems.length === 0, problems, screen: got.screen, state: got.state,
        flag: got.flag, flagCached: got.flagCached, zone: got.zone, zoneCached: got.zoneCached,
        title: got.title, textError: got.textError, screenshot: got.screenshot, texts: got.texts,
        half: pick(got.half), mirror: spec.hooks ? pick(got.mirror) : undefined,
        engageSnap, exits: exitLog.slice(), seq: seq.slice(), ...extra,
      };
      if (spec.store) controls.set(name + ':' + id, { half: row.half, zone: row.zone, screen: row.screen });
      emit(row);
      if (problems.length) throw new Error(id + ' ' + problems.join(','));
      return row;
    };
    const ctx = { s, l, press, dial, idle, engage, check, readLive, readKey, textsOf, exitLog, setMode };
    body(ctx);
  } catch (e) {
    failed = String(e && e.stack ? e.stack : e);
    emit({ session: name, id: 'stopped', role: spec.hooks ? 'behaviour' : 'control', pass: false, problems: ['stopped'], error: failed });
  } finally {
    try { if (pl.session) pl.close_session(); } catch { /* already closed */ }
    writeFileSync(OUT, lines.join('\n') + (lines.length ? '\n' : ''));
  }
  if (failed) throw new Error(name + ' stopped: ' + failed);
}

const normal = (label) => (ctx) => {
  ctx.idle(700);
  ctx.check('base');
  const live = ctx.readLive();
  const via = [ctx.readKey(0x99a1, 0), ctx.readKey(0x99a1, 1), ctx.readKey(0x1dd1, 0)];
  if (via[0] !== live.k99a1[0] || via[1] !== live.k99a1[1] || via[2] !== live.k1dd1[0]) {
    throw new Error('live pointer disagrees with the getter');
  }
  for (let n = 1; n <= 2; n++) {
    if (ctx.s.screen() !== 'shooting') throw new Error(label + n + ' control not on shooting');
    ctx.press('up');
    ctx.check(label + n + '-up');
    ctx.dial('main');
    ctx.check(label + n + '-dial');
    ctx.press('ok');
    ctx.check(label + n + '-ok', { screen: 'shooting' });
  }
};

const sizeOn = (ctx) => {
  ctx.idle(700);
  ctx.check('size-base');
  ctx.press('menu');
  ctx.check('size-menu', { screen: 'menu' });
  let found = false;
  for (let i = 0; i < 24; i++) {
    const texts = ctx.textsOf();
    if (texts.some((t) => String(t).includes('AF Target Settings'))) { found = true; break; }
    ctx.press('left');
    ctx.check('size-tab-' + i);
  }
  if (!found) throw new Error('AF Target Settings not found');
  ctx.press('ok');
  ctx.check('size-page');
  for (let i = 0; i < 5; i++) { ctx.press('down'); ctx.check('size-down-' + i); }
  const before = ctx.readLive();
  ctx.press('right');
  ctx.check('size-right');
  ctx.dial('main');
  ctx.check('size-dial');
  ctx.dial('sub');
  ctx.check('size-sub');
  ctx.press('ok');
  const after = ctx.check('size-ok');
  controls.set('k1:size-before', { half: pick(before) });
  controls.set('k1:size-after', { half: after.half });
};

