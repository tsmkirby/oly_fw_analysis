// Experiment l5. The same exit hook as l3 and l4, not a new behaviour change.
// l4 proved OK (direct-900d), MENU (direct-900e), S1 (direct-972b) and the
// custom-size OK (size-900d). The size compare missed the mirror because the
// field names were decimal. This run names them in hex, then proves playback
// and session end.
// Experiment l4. The same exit hook as l3, not a new behaviour change.
// l3 proved OK: the hook cleared the flag, restored the zone byte, and the
// following edit matched K1 and K2. It then engaged the next exit while the
// direct screen was still open, so this run returns to shooting after every
// normal edit (the control presses OK too) and each AF-ON entry starts there.
// On every exit from the AF-ON editor the
// hook clears 0xa031eef7 and restores the zone byte 0xa031e920 to the value it
// held when the flag became 1 (snapshotted on the first getter or setter, before
// that setter writes the zone). The harness never clears the flag.
// Direct-screen exits are a GUI state leaving 0x0405 (OK 0x900d, MENU 0x900e,
// S1 and playback 0x972b, and a session end that leaves 0x0405). The custom-size
// editor stays on 0x0b02; its Right is 0x900b and its OK/MENU is 0x900d/0x900e.
// Session end also clears at the shutDown entry, because power-off may not post
// a GUI transition before it stops.
// The getter and setter routing is the routing already accepted for this flag.
// The harness copies the current session into the mirror after raising the flag
// so the stock screen can open. That copy is setup, not the initialization change.
// Do not edit this file after it has run.
