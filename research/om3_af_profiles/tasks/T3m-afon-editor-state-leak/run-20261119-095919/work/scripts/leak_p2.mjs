// Experiment p2. One behaviour change, EMULATOR-ONLY.
// The accepted T3l hook stays: entry copies nothing, an FF mirror field
// becomes descriptor 0, and exit clears the flag and restores the zone.
// The one addition is in that same exit. p1 showed the AF-ON screen leaves
// position 994 in three places the next dial reads, and leave() never
// touched them:
//   0x60379d64  16-byte editor record, copied from the object on OK
//               by 0x6119af02 (mov 0x60379d64; 8 halfwords from object+0x42)
//   0x62953c10  settings word, 526 at entry, stored as 994 by the setter
//               body at 0x60063519 and read back by the getter at 0x60063a58
//   object+0x42 the live editor record. The next Up reads it (0x6119de25
//               on the p1 object) and the dial publishes that halfword.
// On exit the global and the settings word return to the bytes snapshotted
// at entry, and the object's position halfword returns to the half-press
// position captured at entry. Values stay in RAM.
// Do not edit this file after it has run.
// Usage: node26 work/scripts/leak_p2.mjs om-emu
