const cellDiffs = (a, b) => {
  const out = [];
  for (const key of CMP) {
    const left = a[key] || [];
    const right = b[key] || [];
    const n = Math.max(left.length, right.length);
    for (let i = 0; i < n; i++) if (left[i] !== right[i]) out.push(key + '[' + i + '] ' + left[i] + ' vs ' + right[i]);
  }
  return out;
};
