// EMULATOR-ONLY pose injection for the stock E147 orientation producer.
// Import this file unchanged. It does not import the emulator.
//
// The pose bytes are written only in the accelerometer's register-read
// stand-in (async read of register 0x20). The native sample completion,
// the native copy, the native correction and the native PER_ROTATE task
// then run. Open, write, close and the data-ready pin setup are stood in
// because this emulator has no I2C bus and no pin 129; they do not supply
// a pose.
//
// attachPose(lab) installs the hooks and calls the stock ACC and PER_ROTATE
// init. The lab must already be open. NVRAM stays the caller's choice.
//
//   const pose = attachPose(lab);
//   pose.setPose('landscape');   // or 'exif6' or 'exif8'
//   pose.deliver();              // one native register read and completion
//   idle so the running tasks publish
//   pose.read();                 // { raw, index, exif, ... }
//
// Measured on the stock image (trace-pose-s4): sensor LSB, 16384 = 1 g.
//   landscape  (0, -16384, 0)  raw 0  index 1  EXIF 1
//   exif6      (16384, 0, 0)   raw 1  index 2  EXIF 6
//   exif8      (-16384, 0, 0)  raw 3  index 4  EXIF 8
// raw is the halfword at 0xa32c5690. index is the word at 0xa32c568c.
// EXIF is the native getter 0x60077de1. Do not edit this file after it has run.

export const IMAGE_BASE = 0x60021020;
export const LABEL = 'EMULATOR-ONLY';

export function disasm(address) {
  return (0x50000000 + address - IMAGE_BASE) >>> 0;
}

const G = 16384;
export const POSES = {
  landscape: { x: 0, y: -G, z: 0, raw: 0, index: 1, exif: 1 },
  exif6: { x: G, y: 0, z: 0, raw: 1, index: 2, exif: 6 },
  exif8: { x: -G, y: 0, z: 0, raw: 3, index: 4, exif: 8 },
};

const ACC_INIT = 0x6006a436;
const ROTATE_INIT = 0x60077d18;
const DEVICE_CALL = 0x6006a43d;
const OPEN = 0x6006f1bf;
const ASYNC_READ = 0x6006f28e;
const CLOSE = 0x6006f39a;
const SYNC_READ = 0x6006f3a5;
const SYNC_WRITE = 0x6006f3bb;
const ISSUE = 0x6006a8ab;
const COMPLETION = 0x6006a8ca;
const PUBLISH = 0x6007805e;
const RAW = 0xa32c5690;
const INDEX = 0xa32c568c;
const FLAG = 0xa32c5688;
const ENABLE = 0x6298d7b0;
const STATE = 0x6298e3f4;
const UNPACKED = 0x6298d7ce;
const CACHE = 0x6298d758;
const EXIF_GET = 0x60077de1;

function sampleBytes(x, y, z) {
  const b = new Uint8Array(14);
  const put = (off, v) => {
    const n = (v < 0 ? v + 65536 : v) & 0xffff;
    b[off] = n & 0xff;
    b[off + 1] = (n >> 8) & 0xff;
  };
  put(8, x);
  put(10, y);
  put(12, z);
  return b;
}

export function attachPose(lab) {
  const sim = lab.sim;
  let sample = sampleBytes(0, -G, 0);
  const counts = {};
  const publishes = [];
  const bump = (name) => { counts[name] = (counts[name] || 0) + 1; };
  const u16 = (a) => { const b = sim.read(a, 2); return b[0] | (b[1] << 8); };
  const i16 = (a) => { const v = u16(a); return v & 0x8000 ? v - 0x10000 : v; };

  lab.hook(disasm(DEVICE_CALL), (h, r) => { bump('skip-device'); h.skip_call(r); }, LABEL + ' acc pin setup skipped');
  lab.hook(disasm(OPEN), (h, r) => { bump('open'); h.finish(r, { d0: 0 }); }, LABEL + ' acc bus open');
  lab.hook(disasm(CLOSE), (h, r) => { bump('close'); h.finish(r, { d0: 0 }); }, LABEL + ' acc bus close');
  lab.hook(disasm(SYNC_WRITE), (h, r) => { bump('write'); h.finish(r, { d0: 0 }); }, LABEL + ' acc register write');
  lab.hook(disasm(SYNC_READ), (h, r) => {
    bump('sync-read');
    const n = Math.min(r.a1 >>> 0, 16);
    const bytes = new Uint8Array(n);
    if ((r.d1 & 0xff) === 0x0f && n >= 1) bytes[0] = 0x70;
    if (n) sim.write(r.a0 >>> 0, bytes);
    h.finish(r, { d0: 0 });
  }, LABEL + ' acc sync register read');
  lab.hook(disasm(ASYNC_READ), (h, r) => {
    bump('async-read');
    if ((r.d1 & 0xff) === 0x20) sim.write(r.a0 >>> 0, sample);
    else sim.write(r.a0 >>> 0, new Uint8Array(14));
    h.finish(r, { d0: 0 });
  }, LABEL + ' acc sample register read');
  lab.observe(disasm(PUBLISH), (_lab, r) => {
    bump('publish');
    if (publishes.length < 24) publishes.push(r.d0 & 0xffff);
  }, 'obs-pose-publish');

  for (const entry of [0x6006a660, 0x6006a720, 0x60077e0a, 0x6007d7bb]) lab.lt.allow.add(disasm(entry));
  lab.call(disasm(ACC_INIT), null, null, null, 1000000);
  lab.call(disasm(ROTATE_INIT), null, null, null, 1000000);

  return {
    counts,
    publishes,
    setSample(x, y, z) { sample = sampleBytes(x, y, z); },
    setPose(name) {
      const pose = POSES[name];
      if (!pose) throw new Error('unknown pose ' + name);
      sample = sampleBytes(pose.x, pose.y, pose.z);
      return pose;
    },
    deliver() {
      const before = counts['async-read'] || 0;
      lab.call(disasm(ISSUE), null, null, [0, 0], 200000);
      lab.call(disasm(COMPLETION), null, null, [0, 0], 200000);
      return { readFired: (counts['async-read'] || 0) > before, counts: { ...counts } };
    },
    read() {
      let exif = null;
      try { exif = lab.call(disasm(EXIF_GET), null, null, null, 200000).d0 & 0xffff; } catch (e) { exif = null; }
      return {
        raw: u16(RAW),
        index: sim.u32(INDEX) >>> 0,
        flag: sim.u32(FLAG) >>> 0,
        exif,
        enable: u16(ENABLE),
        state: sim.u32(STATE) >>> 0,
        unpacked: [i16(UNPACKED), i16(UNPACKED + 2), i16(UNPACKED + 4)],
        cache: [i16(CACHE), i16(CACHE + 2), i16(CACHE + 4)],
        counts: { ...counts },
        publishes: publishes.slice(),
      };
    },
  };
}
