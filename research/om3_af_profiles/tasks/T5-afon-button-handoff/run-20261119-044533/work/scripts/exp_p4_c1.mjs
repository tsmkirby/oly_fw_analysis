// P4. The legacy AF Home zone and the RAM profile zone are different values.
// Explanation first: profile UI value 1 is Single. 0x9fa1 index 0 is written to 2,
// which is Small. The legacy provider would feed the converter UI value 2 and the
// AF-ON record would be the Small record 0e 02 03 00 01 00 01 00 00 00. The profile
// read has to keep the Single record 0e 02 00 00 01 00 01 00 00 00 on every AF-ON
// edge. Half-press edges stay on the half-press record. A no-overlay control gets
// the same 0x9fa1 write and the same 12 edges. Its target is the stock literal
// 0e 02 02 00 1b 00 27 00 00 00 on every edge.
// Do not edit this file after it has run.
// Usage: node26 work/scripts/exp_p4_c1.mjs om-emu
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { runZone } from './zone_session_k1.mjs';

const [checkout] = process.argv.slice(2);
if (!checkout) {
  process.stderr.write('usage: node26 work/scripts/exp_p4_c1.mjs om-emu\n');
  process.exit(2);
}
const OUT = resolve('work/out/edges-p4-c1.jsonl');
const lines = [];
const emit = (row) => {
  lines.push(JSON.stringify(row));
  console.log(JSON.stringify(row));
  mkdirSync(resolve('work/out'), { recursive: true });
  writeFileSync(OUT, lines.join('\n') + '\n');
};
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const SINGLE = [0x0e, 0x02, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00];
const SMALL = [0x0e, 0x02, 0x03, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00];
const HALF = [0x0e, 0x02, 0x03, 0x00, 0x03, 0x00, 0x03, 0x00, 0x00, 0x00];
const STOCK = [0x0e, 0x02, 0x02, 0x00, 0x1b, 0x00, 0x27, 0x00, 0x00, 0x00];
const EDGES = [
  ['s1', 'down'], ['s1', 'up'],
  ['afon', 'down'], ['afon', 'up'],
  ['s1', 'down'], ['afon', 'down'], ['afon', 'up'], ['s1', 'up'],
  ['afon', 'down'], ['s1', 'down'], ['s1', 'up'], ['afon', 'up'],
];
const OWNERS = [1, 0, 2, 0, 1, 2, 1, 0, 2, 2, 2, 0];
const HALF_AT = new Set([0, 1, 3, 4, 6, 7, 11]);
const CELLS = {
  k90a1: [1, 1],
  k1dd1: [3, 3, 3, 3, 3, 3, 3, 3, 3, 3],
  k99a1: [2, 0, 2, 0, 2, 0, 5, 5],
  k9a41: 0,
  k5962: [526, 526, 526, 526, 526, 526],
  home: {
    '0x99d2': [526, 526, 526], '0x9fa1': [2, 0, 0], '0xdfa1': [0], '0x1ea1': [0],
    '0x9ec1': [0], '0x9ed1': [1], '0x9ee1': [0], '0x9ef1': [0], '0x59b1': [0],
  },
};

emit({
  experiment: 'p4',
  record: 'explanation',
  text: 'Profile UI value 1 is Single. Legacy 0x9fa1 index 0 is set to 2, Small, so the two providers disagree. The AF-ON edges must keep the Single record. The Small record is what UI value 2 produces and must not appear. The no-overlay control uses the same 0x9fa1 write and the same 12 edges, and every control target is the stock literal 0e 02 02 00 1b 00 27 00 00 00.',
});

function writeSetting(ctx, key, index, value) {
  return ctx.l.call(ctx.native(0x60063431), { d0: key, d1: index, a0: 0, a1: value }, null, null, 200000).d0 >>> 0;
}
function readSetting(ctx, key, index) {
  return ctx.l.call(ctx.native(0x60063380), { d0: key, d1: index, a0: 0 }, null, null, 200000).d0 & 0xffff;
}
function watched(ctx) {
  const cells = ctx.cells();
  return {
    k90a1: cells.k90a1, k1dd1: cells.k1dd1, k99a1: cells.k99a1,
    k9a41: cells.k9a41, k5962: cells.k5962, home: cells.home,
  };
}
async function prepare(ctx) {
  const { A } = await import(pathToFileURL(resolve(checkout, 'emu/src/fw/model.mjs')).href);
  const api = A(0x50ac4afe);
  ctx.bringUp();
  ctx.s.switch_input('lever', 1);
  ctx.s.camapp.pump();
  ctx.idle(500);
  const argument = ctx.l.call(ctx.native(0x604050e5), { d0: 289, d1: 0 }, null, null, 200000).d0 >>> 0;
  ctx.l.call(api, { d0: 289, d1: argument }, null, null, 200000);
  ctx.l.call(api, { d0: 1712, d1: 0 }, null, null, 200000);
  ctx.idle(500);
}
function chooseSingle(ctx) {
  ctx.press('menu');
  for (let i = 0; i < 20; i++) ctx.press('left');
  ctx.press('down');
  ctx.press('down');
  ctx.press('ok');
  ctx.press('down');
  ctx.press('down');
  ctx.press('ok');
  ctx.press('right');
  ctx.shot('zone-1');
  ctx.press('ok');
  for (let i = 0; i < 8 && ctx.s.screen() !== 'shooting'; i++) ctx.press('menu');
}
function checkEdge(ctx, name, index) {
  const shot = ctx.shot('edge-' + index);
  if (!shot.file) throw new Error('screenshot missing at edge ' + index);
  const cells = watched(ctx);
  const own = ctx.readOwn();
  const got = {
    target: ctx.readTarget(),
    owner: ctx.candidate ? own[4] : null,
    status: ctx.candidate ? own[5] : null,
    enabled: ctx.candidate ? own[6] : null,
    profile: ctx.readByte(ctx.PROFILE),
    focus: ctx.s.get(289),
    subject: ctx.s.get(1712),
    cells,
    home9fa1: cells.home['0x9fa1'][0],
  };
  const target = ctx.candidate ? (HALF_AT.has(index) ? HALF : SINGLE) : STOCK;
  const problems = [];
  if (!same(got.target, target)) problems.push('target');
  if (same(got.target, SMALL)) problems.push('followed-legacy-small');
  if (got.focus !== 0) problems.push('focus');
  if (got.subject !== 0) problems.push('subject');
  if (!same(got.cells, CELLS)) problems.push('cells');
  if (got.home9fa1 !== 2) problems.push('9fa1');
  if (ctx.candidate) {
    if (got.profile !== 1) problems.push('profile');
    if (got.owner !== OWNERS[index]) problems.push('owner');
    if (got.status !== 0) problems.push('status');
    if (got.enabled !== 1) problems.push('enabled');
  }
  emit({
    experiment: 'p4', session: name, edge: index, key: EDGES[index][0], dir: EDGES[index][1],
    pass: problems.length === 0, problems, got,
    expect: { target, owner: ctx.candidate ? OWNERS[index] : null, profile: ctx.candidate ? 1 : null, home9fa1: 2 },
    screenshot: shot.file.split(/[/\\]/).pop(),
  });
  if (problems.length) throw new Error(name + ' edge ' + index + ' ' + problems.join(','));
}

async function lane(name, candidate, drive) {
  const result = await runZone({
    checkout,
    outPath: 'work/out/session-p4-c1-' + name + '.jsonl',
    tag: 'p4-c1-' + name,
    candidate,
    help: true,
    rowLabel: true,
    overlayCsv: candidate ? 'work/out/overlay-changed-bytes.csv' : null,
    fatalShots: true,
    explanation: candidate
      ? 'P4 candidate. Profile Single, legacy 0x9fa1 Small. Role: behaviour. EMULATOR-ONLY.'
      : 'P4 no-overlay control. Same 0x9fa1 write and the same 12 edges. Stock target on every edge.',
    change: candidate ? 'profile source swap, plus one AF Home write as the negative control' : 'one AF Home write, no AF-ON overlay',
    drive,
  });
  if (!result.ok) throw new Error(name + ' failed: ' + result.failed);
}

try {
  await lane('control', false, async (ctx) => {
    await prepare(ctx);
    const wrote = writeSetting(ctx, 0x9fa1, 0, 2);
    const home = readSetting(ctx, 0x9fa1, 0);
    emit({ experiment: 'p4', session: 'control', record: 'wrote-9fa1', wrote, home, value: 2 });
    if (home !== 2) throw new Error('control 0x9fa1 ' + home);
    for (let i = 0; i < EDGES.length; i++) {
      ctx.key(EDGES[i][0], EDGES[i][1]);
      ctx.idle(600);
      checkEdge(ctx, 'control', i);
    }
  });
  await lane('candidate', true, async (ctx) => {
    await prepare(ctx);
    chooseSingle(ctx);
    if (ctx.s.screen() !== 'shooting') throw new Error('not shooting');
    if (ctx.readByte(ctx.PROFILE) !== 1) throw new Error('profile ' + ctx.readByte(ctx.PROFILE));
    const wrote = writeSetting(ctx, 0x9fa1, 0, 2);
    const home = readSetting(ctx, 0x9fa1, 0);
    emit({ experiment: 'p4', session: 'candidate', record: 'wrote-9fa1', wrote, home, profile: ctx.readByte(ctx.PROFILE), value: 2 });
    if (home !== 2) throw new Error('candidate 0x9fa1 ' + home);
    for (let i = 0; i < EDGES.length; i++) {
      ctx.key(EDGES[i][0], EDGES[i][1]);
      ctx.idle(600);
      checkEdge(ctx, 'candidate', i);
    }
  });
  emit({ record: 'done', ok: true });
} catch (e) {
  emit({ record: 'done', ok: false, error: String(e && e.stack ? e.stack : e) });
  process.exitCode = 1;
}
